import js from "@eslint/js";
import tseslint from "typescript-eslint";
import reactHooks from "eslint-plugin-react-hooks";

/**
 * Flat ESLint config for the whole monorepo.
 *
 * Deliberately single-config rather than per-workspace: the three packages share a language and a
 * style, and one config means a rule cannot drift between them.
 *
 * Type-aware linting (`projectService`) is intentionally NOT enabled. It roughly triples lint time
 * and mostly duplicates what `tsc --noEmit` already enforces in CI — the type checker is the
 * authority on types; ESLint covers what it does not.
 */
export default tseslint.config(
  {
    ignores: [
      "**/dist/**",
      "**/node_modules/**",
      "**/coverage/**",
      // Generated by Prisma; not ours to lint.
      "server/prisma/migrations/**",
      // The original design specs. These are reference documents that happen to contain TSX, not
      // source that ships — `consultation-booking.tsx` is a fragment and does not parse.
      "docs/**",
    ],
  },

  js.configs.recommended,
  ...tseslint.configs.recommended,

  {
    rules: {
      // Unused args are usually intentional in signatures (Express handlers, React props).
      "@typescript-eslint/no-unused-vars": [
        "warn",
        { argsIgnorePattern: "^_", varsIgnorePattern: "^_", caughtErrorsIgnorePattern: "^_" },
      ],
      // `catch {}` around localStorage is deliberate: private browsing throws, and there is nothing
      // useful to do about it.
      "no-empty": ["error", { allowEmptyCatch: true }],
      // The codebase uses `void promise` and `??=` deliberately; neither is a mistake.
      "no-void": "off",
    },
  },

  {
    // React hooks rules only where React is used. Wiring the plugin is what makes the existing
    // `eslint-disable-next-line react-hooks/exhaustive-deps` comments meaningful rather than errors.
    files: ["client/**/*.{ts,tsx}"],
    plugins: { "react-hooks": reactHooks },
    rules: {
      ...reactHooks.configs.recommended.rules,
    },
  },

  {
    files: ["**/*.config.{js,mjs,ts}", "**/*.mjs"],
    rules: { "@typescript-eslint/no-require-imports": "off" },
  },
);
